/**
 * Builds src/lib/imageDimensions.generated.ts: the pixel size of every image in
 * static/ that a page might reference in an og:image tag.
 *
 * Why generated rather than measured at request time: og:image:width and
 * og:image:height have to be in the HTML head, the head is rendered on every
 * request, and stat-ing image files per request to fill them in would be waste.
 * A hardcoded table would go stale the moment a post ships with a new image, so
 * this reads the real files and is re-run alongside the build.
 *
 * Headers are parsed directly, so this needs no image dependency.
 *
 * Run it after adding an image: `npm run images`.
 */
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, extname, relative } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const STATIC = join(ROOT, 'static');
const EXTS = new Set(['.png', '.jpg', '.jpeg', '.gif', '.webp']);

/** PNG: an 8-byte signature, then an IHDR chunk carrying width and height. */
function png(buf) {
	if (buf.length < 24) return null;
	if (buf.readUInt32BE(0) !== 0x89504e47) return null;
	return { width: buf.readUInt32BE(16), height: buf.readUInt32BE(20) };
}

/**
 * JPEG: walk the segment chain to a Start Of Frame marker. The dimensions are
 * not at a fixed offset, because how many segments precede the frame depends on
 * what the encoder wrote (EXIF, ICC profiles, comments).
 */
function jpeg(buf) {
	if (buf.length < 4 || buf.readUInt16BE(0) !== 0xffd8) return null;
	let i = 2;
	while (i < buf.length - 9) {
		if (buf[i] !== 0xff) {
			i++;
			continue;
		}
		const marker = buf[i + 1];
		// SOF0 through SOF15 carry the frame header. C4 (Huffman table), C8
		// (JPEG extension) and CC (arithmetic coding) sit in the same range and
		// are not frames.
		const isFrame =
			marker >= 0xc0 && marker <= 0xcf && marker !== 0xc4 && marker !== 0xc8 && marker !== 0xcc;
		if (isFrame) {
			return { height: buf.readUInt16BE(i + 5), width: buf.readUInt16BE(i + 7) };
		}
		if (marker === 0xd8 || (marker >= 0xd0 && marker <= 0xd9)) {
			i += 2;
			continue;
		}
		i += 2 + buf.readUInt16BE(i + 2);
	}
	return null;
}

/** GIF: fixed header, little-endian. */
function gif(buf) {
	if (buf.length < 10 || buf.toString('ascii', 0, 3) !== 'GIF') return null;
	return { width: buf.readUInt16LE(6), height: buf.readUInt16LE(8) };
}

/** WebP: three encodings, each storing the size differently. */
function webp(buf) {
	if (buf.length < 30) return null;
	if (buf.toString('ascii', 0, 4) !== 'RIFF' || buf.toString('ascii', 8, 12) !== 'WEBP') return null;
	const fmt = buf.toString('ascii', 12, 16);
	if (fmt === 'VP8 ') {
		return { width: buf.readUInt16LE(26) & 0x3fff, height: buf.readUInt16LE(28) & 0x3fff };
	}
	if (fmt === 'VP8L') {
		const bits = buf.readUInt32LE(21);
		return { width: (bits & 0x3fff) + 1, height: ((bits >> 14) & 0x3fff) + 1 };
	}
	if (fmt === 'VP8X') {
		const w = buf[24] | (buf[25] << 8) | (buf[26] << 16);
		const h = buf[27] | (buf[28] << 8) | (buf[29] << 16);
		return { width: w + 1, height: h + 1 };
	}
	return null;
}

function dimensionsOf(file) {
	// 64KB is well past any header, including a fat EXIF block, and avoids
	// pulling multi-megabyte photographs into memory to read eight bytes.
	const buf = readFileSync(file).subarray(0, 65536);
	switch (extname(file).toLowerCase()) {
		case '.png':
			return png(buf);
		case '.jpg':
		case '.jpeg':
			return jpeg(buf);
		case '.gif':
			return gif(buf);
		case '.webp':
			return webp(buf);
		default:
			return null;
	}
}

const found = [];
const skipped = [];
(function walk(dir) {
	for (const entry of readdirSync(dir, { withFileTypes: true })) {
		const p = join(dir, entry.name);
		if (entry.isDirectory()) {
			walk(p);
		} else if (EXTS.has(extname(entry.name).toLowerCase())) {
			// The public URL is the path under static/, with a leading slash.
			const url = '/' + relative(STATIC, p).split('\\').join('/');
			try {
				const d = dimensionsOf(p);
				if (d && d.width > 0 && d.height > 0) found.push([url, d]);
				else skipped.push(url);
			} catch {
				skipped.push(url);
			}
		}
	}
})(STATIC);

found.sort((a, b) => a[0].localeCompare(b[0]));

const out = `// GENERATED BY scripts/generate-image-dimensions.mjs - DO NOT EDIT BY HAND.
// Regenerate with: npm run images
// ${found.length} images measured from static/.

export type ImageSize = { width: number; height: number };

const SIZES: Record<string, ImageSize> = {
${found.map(([url, d]) => `\t'${url}': { width: ${d.width}, height: ${d.height} }`).join(',\n')}
};

/**
 * Pixel size of an image served from static/, or null when it is unknown.
 * Callers must treat null as "omit the dimension tags" rather than guessing:
 * a wrong og:image:width is worse than an absent one, because a scraper will
 * lay the card out to the size we claim.
 */
export function imageSize(path: string | null | undefined): ImageSize | null {
	if (!path) return null;
	const clean = path.split('?')[0];
	return SIZES[clean] ?? null;
}
`;

writeFileSync(join(ROOT, 'src/lib/imageDimensions.generated.ts'), out);
console.log(`imageDimensions.generated.ts: measured ${found.length} images`);
if (skipped.length) console.log(`  unreadable, omitted: ${skipped.join(', ')}`);
